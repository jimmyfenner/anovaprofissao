-- =========================================================
-- A NOVA PROFISSÃO — diário de reuniões do Jimmy (nov/2026)
--
-- Página anovaprofissao.com.br/reunioes (mesmo login do /admin): leads das
-- chamadas do Google Meet, status das reuniões, lembretes, comentários e envio
-- de mensagem ao lead. Quem preenche é o assistente do Mac do Jimmy
-- (Reunioes/_ferramentas/assistente): a rotina lê as transcrições e grava aqui,
-- e o ciclo manda os lembretes no WhatsApp (1575) e lê as respostas dele.
--
--   reunioes_leads        uma linha por pessoa (situação, temperatura, contato)
--   reunioes              uma linha por reunião (doc:<id do Gemini> ou evt:<id do evento>)
--   reunioes_lembretes    lembretes do Jimmy (o ciclo do Mac manda no WhatsApp)
--   reunioes_comentarios  anotações livres por lead
--   reunioes_envios       mensagens mandadas ao lead pelo painel (com o erro, se houver)
--   reunioes_config       hash do token do assistente do Mac
--
-- RLS ligada e nenhuma policy: nada é lido nem gravado pela API pública.
-- Tudo passa pela Edge Function `reunioes` (service role), que confere o
-- login do painel ou o token do Mac.
--
-- Pode ser executado mais de uma vez sem efeito colateral.
-- =========================================================

create table if not exists public.reunioes_leads (
  id              uuid primary key default gen_random_uuid(),
  nome            text not null check (length(nome) between 1 and 200),
  telefone        text,
  cidade          text,
  empresa         text,
  produto         text,
  situacao        text not null default 'aberto' check (situacao in ('aberto','ganho','perdido','pausado')),
  temperatura     text check (temperatura in ('quente','morno','frio')),
  temperatura_por text,             -- 'jimmy' quando ele trocou no painel (a rotina não sobrescreve)
  instancia       text,             -- de qual WhatsApp mandar mensagem a este lead
  criado_em       timestamptz not null default now(),
  atualizado_em   timestamptz not null default now()
);
create index if not exists reunioes_leads_telefone_idx on public.reunioes_leads (telefone);

create table if not exists public.reunioes (
  chave              text primary key,
  lead_id            uuid references public.reunioes_leads(id) on delete cascade,
  doc_id             text,
  event_id           text,
  data               date,
  hora               text,
  inicio             timestamptz,
  fim                timestamptz,
  duracao_min        int,
  titulo             text,
  tipo               text,
  produto            text,
  status             text,
  status_por         text,
  status_em          timestamptz,
  temperatura        text,
  temperatura_porque text,
  resumo             text,
  objecoes           jsonb not null default '[]'::jsonb,
  proximos_passos    jsonb not null default '[]'::jsonb,
  nota               text,
  perguntado_em      timestamptz,
  remarcada_para     timestamptz,
  criado_em          timestamptz not null default now(),
  atualizado_em      timestamptz not null default now()
);
create index if not exists reunioes_lead_idx on public.reunioes (lead_id);
create index if not exists reunioes_event_idx on public.reunioes (event_id);

create table if not exists public.reunioes_lembretes (
  id            bigint generated by default as identity primary key,
  texto         text not null check (length(texto) between 1 and 1000),
  quando        timestamptz not null,
  reuniao       text references public.reunioes(chave) on delete set null,
  lead_id       uuid references public.reunioes_leads(id) on delete cascade,
  lead          text,
  telefone      text,
  origem        text,
  origem_texto  text,
  status        text not null default 'pendente' check (status in ('pendente','enviado','feito','apagado')),
  adiamentos    jsonb not null default '[]'::jsonb,
  criado_em     timestamptz not null default now(),
  enviado_em    timestamptz,
  feito_em      timestamptz,
  apagado_em    timestamptz,
  atualizado_em timestamptz not null default now()
);
create index if not exists reunioes_lembretes_aberto_idx on public.reunioes_lembretes (status, quando);

create table if not exists public.reunioes_comentarios (
  id        bigint generated by default as identity primary key,
  lead_id   uuid not null references public.reunioes_leads(id) on delete cascade,
  texto     text not null check (length(texto) between 1 and 4000),
  criado_em timestamptz not null default now()
);
create index if not exists reunioes_comentarios_lead_idx on public.reunioes_comentarios (lead_id, criado_em desc);

create table if not exists public.reunioes_envios (
  id        bigint generated by default as identity primary key,
  lead_id   uuid references public.reunioes_leads(id) on delete set null,
  telefone  text not null,
  instancia text not null,
  texto     text not null,
  status    text not null check (status in ('ok','erro','incerto')),
  erro      text,
  criado_em timestamptz not null default now()
);
create index if not exists reunioes_envios_lead_idx on public.reunioes_envios (lead_id, criado_em desc);

create table if not exists public.reunioes_config (
  id         int primary key default 1 check (id = 1),
  token_hash text not null
);
